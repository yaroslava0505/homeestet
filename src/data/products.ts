const PRODUCTS_BY_ID = new Map(PRODUCTS_CATALOG.map((p) => [p.id, p]));

/** Looks a product up by id. Throws at module load time if data references a missing product. */
export function getProduct(id: string): ProductItem {
  const product = PRODUCTS_BY_ID.get(id);
  if (!product) throw new Error(`Unknown product id: ${id}`);
  return product;
}

export function findProduct(id: string): ProductItem | undefined {
  return PRODUCTS_BY_ID.get(id);
}
